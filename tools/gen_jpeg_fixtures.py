"""Generate JPEG oracle fixtures for the zig-image-codec decoder.

Cross-validates the pure-Zig baseline JPEG entropy decoder against libjpeg
(via the `jpeglib` package, which returns the exact quantized DCT
coefficients of `jpeg_read_coefficients`).

For each fixture it writes:
  - src/fixtures/oracle_<name>.jpg : the baseline JPEG bytes (with a synthetic
    EXIF APP1 carrying the dead-drop salt material fields)
  - src/oracle_<name>.zig          : expected carrier array + geometry + material

Regenerate with:
    pip install pillow jpeglib
    python tools/gen_jpeg_fixtures.py
"""

