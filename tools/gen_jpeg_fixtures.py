AC_BAND_LO = 1
AC_BAND_HI = 32
BPP = AC_BAND_HI - AC_BAND_LO + 1

# Deterministic EXIF fields for the synthetic covers (fixtures only; real
# dead-drop covers are real camera photos whose own EXIF is never modified).
FIXTURE_MAKE = "HUAWEI"
FIXTURE_MODEL = "ELS-AN10"
FIXTURE_DT = "2026:08:02 11:39:40"
FIXTURE_SUBSEC = "229502"


def make_texture(width, height):
    """Deterministic textured image (gradient + waves) with rich AC energy."""
    img = Image.new("RGB", (width, height))
    px = img.load()
    for y in range(height):
        for x in range(width):
            r = (x * 7 + y * 3) % 256
            g = (x * 11 + y * 5 + 40) % 256
            b = int(128 + 96 * math.sin(x / 6.0) * math.cos(y / 5.0)) % 256
            px[x, y] = (r, g, b)
    return img


def fixture_exif(width, height):
    """Synthetic EXIF APP1 payload (well-formed TIFF, II endian)."""
    return exif_tool.build_exif(FIXTURE_MAKE, FIXTURE_MODEL, FIXTURE_DT, FIXTURE_SUBSEC, width, height)


def write_zig(path, name, blocks_x, blocks_y, carriers, material):
    def arr(prefix, vals, indent=4):
        lines = []
        for i in range(0, len(vals), 16):
            chunk = ", ".join(str(v) for v in vals[i : i + 16])
            lines.append(" " * indent + chunk + ",")
        return f"pub const {prefix} = [_]u8{{\n" + "\n".join(lines) + "\n};\n"

    with open(path, "w", encoding="utf-8") as f:
        f.write("//! Auto-generated by tools/gen_jpeg_fixtures.py - do not edit.\n")
        f.write(f"//! libjpeg oracle for the {name} fixture.\n\n")
        f.write(f"pub const BLOCKS_X: u32 = {blocks_x};\n")
        f.write(f"pub const BLOCKS_Y: u32 = {blocks_y};\n")
        f.write(f'pub const MATERIAL_HEX = "{material.hex()}";\n\n')
        f.write(arr("carriers", carriers))
    import subprocess

    subprocess.run(["zig", "fmt", path], check=True)


def build(name, mode, blocks_x, blocks_y):
    import io
    import tempfile

    width, height = blocks_x * 8, blocks_y * 8
    img = make_texture(width, height)
    if mode == "gray":
        img = img.convert("L")

    buf = io.BytesIO()
    if mode == "color":
        img.save(buf, "JPEG", quality=90, subsampling=2, exif=fixture_exif(width, height))  # 4:2:0
    else:
        img.save(buf, "JPEG", quality=90, exif=fixture_exif(width, height))
    jpg = buf.getvalue()

    import jpeglib

    with tempfile.NamedTemporaryFile(suffix=".jpg", delete=False) as tmp:
        tmp_path = tmp.name
        tmp.write(jpg)
    try:
        dct = jpeglib.read_dct(tmp_path)
    finally:
        os.unlink(tmp_path)

    y = dct.Y
    if y is None and mode == "gray":
        # Grayscale may surface as a single plane regardless of name.
        for p in (dct.Cb, dct.Cr):
            if p is not None:
                y = p
                break
    assert y is not None, "no Y plane from jpeglib"
    ny, nx = y.shape[0], y.shape[1]
    assert (nx, ny) == (blocks_x, blocks_y), (nx, ny, blocks_x, blocks_y)

    carriers = []
    for by in range(ny):
        for bx in range(nx):
            for z in range(AC_BAND_LO, AC_BAND_HI + 1):
                nat = ZIGZAG[z]
                val = int(y[by, bx, nat // 8, nat % 8])
                mag = abs(val)
                carriers.append(mag if 2 <= mag <= 254 else 0)

    material = exif_tool.derive_material(FIXTURE_MAKE, FIXTURE_MODEL, FIXTURE_DT, FIXTURE_SUBSEC, width, height)

    fixture_dir = os.path.join(
        os.path.dirname(os.path.abspath(__file__)), "..", "src", "fixtures"
    )
    os.makedirs(fixture_dir, exist_ok=True)
    fixture_path = os.path.join(fixture_dir, f"oracle_{name}.jpg")
    with open(fixture_path, "wb") as f:
        f.write(jpg)

    out_zig = os.path.join(
        os.path.dirname(os.path.abspath(__file__)), "..", "src", f"oracle_{name}.zig"
    )
    write_zig(out_zig, name, nx, ny, carriers, material)
    nz = sum(1 for c in carriers if c != 0)
    print(f"{name}: {nx}x{ny} blocks, {len(carriers)} carriers, {nz} nonzero")


def main():
    build("color", "color", 8, 6)
    build("gray", "gray", 7, 5)


if __name__ == "__main__":
    main()
